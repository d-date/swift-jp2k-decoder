#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
source="${OPJ_SRC:-$root/.reference/openjpeg}/tests/conformance/CMakeLists.txt"
output="$root/Tests/JP2KTests/Support/ConformanceTable.swift"
python3 -I - "$source" "$output" <<'PY'
import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1])
output = pathlib.Path(sys.argv[2])
tables = dict(re.findall(r'^set\(\s*(\w+)\s*"([^"]*)"\)', source.read_text(), re.MULTILINE))

def field(key, index):
    return tables[key].split(';')[index]

def numbers(value):
    return '[' + ', '.join(value.split(':')) + ']'

lines = [
    '// Generated by Scripts/make-conformance-table.sh from OpenJPEG v2.5.4',
    '// tests/conformance/CMakeLists.txt (BSD-2-Clause). Do not edit by hand.',
    '// See THIRD_PARTY/openjpeg-LICENSE and docs/provenance.md.',
    '',
    'enum ConformanceTable {',
    '    static let class1: [ConformanceCase] = [',
]
for profile, last in ((0, 16), (1, 7)):
    for index in range(1, last + 1):
        number = f'{index:02d}'
        prefix = f'C1P{profile}'
        count = int(field(f'CP{profile}_nbC_list', index))
        factor = int(field('C1P0_ResFactor_list', index)) if profile == 0 else 0
        peak = numbers(field(f'{prefix}_PEAK_list', index))
        mse = numbers(field(f'{prefix}_MSE_list', index))
        lines.append(
            f'        ConformanceCase(name: "p{profile}_{number}.j2k", '
            f'referenceStem: "c1p{profile}_{number}", componentCount: {count}, '
            f'resFactor: {factor}, peak: {peak}, mse: {mse}),'
        )
lines += ['    ]', '}', '']
output.write_text('\n'.join(lines))
PY
