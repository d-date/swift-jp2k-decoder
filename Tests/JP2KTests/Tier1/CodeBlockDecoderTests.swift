// Generated by Scripts/make-codeblock-trace.sh from OpenJPEG v2.5.4.
// Each row is the complete signed Int32 t1->data buffer immediately after
// opj_t1_decode_cblk, before ROI adjustment and dequantisation.
@Test(arguments: ["gray-378x472-53", "gray-378x472-97", "rgb-64-53-mct", "rgb-64-97",
                  "cblk-8x8", "modes-all", "modes-bypass"])
func codeBlocksMatchOpenJPEG(_ name: String) throws {
    let input = name == "gray-378x472-53" || name == "cblk-8x8" || name.hasPrefix("modes-") ?
        "\(name).j2k" : "\(name).jp2"
    let candidates = try blocks(input)
    let trace = String(decoding: try Data(contentsOf: #require(Fixtures.url("codeblock-\(name).txt"))), as: UTF8.self)
    var budget = MemoryBudget(limit: 1 << 24)
    var decoder = try CodeBlockDecoder(maxWidth: 64, maxHeight: 64, budget: &budget)
    if name == "cblk-8x8" || name.hasPrefix("modes-") {
        #expect(trace.split(separator: "\n").count == candidates.count)
    }
    var samples: [Int32] = []
    var matchedIndices = Set<Int>()
    for line in trace.split(separator: "\n") {
        let fields = try line.split(separator: " ").dropFirst().map { try #require(Int($0)) }
        _ = try #require(fields.count >= 8)
        let index = try #require(candidates.indices.first { candidateIndex in
            let item = candidates[candidateIndex]
            return !matchedIndices.contains(candidateIndex) &&
                item.0.x0 == fields[1] && item.0.y0 == fields[2] &&
                item.0.x1 == fields[3] && item.0.y1 == fields[4] &&
                item.1 == fields[5] && item.2 == fields[6]
        })
        matchedIndices.insert(index)
        let matching = candidates[index]
        let style: UInt8 = name == "modes-all" ? 63 : (name == "modes-bypass" ? 1 : 0)
        try decoder.decode(matching.0, orientation: matching.1, roiShift: 0,
                           codeBlockStyle: style, numBitPlanes: matching.2, budget: &budget); samples = decoder.outputArray()
        #expect(samples == fields.dropFirst(7).map(Int32.init))
    }
}

@Test func zeroLevelBlocksMatchPixels() throws {
    let image = try PGX.parse(Array(Data(contentsOf: #require(Fixtures.url("levels-0_0.pgx")))))
    let candidates = try blocks("levels-0.j2k")
    var budget = MemoryBudget(limit: 1 << 24)
    var decoder = try CodeBlockDecoder(maxWidth: 64, maxHeight: 64, budget: &budget)
    var samples: [Int32] = []
    for (block, orientation, bitPlanes) in candidates where block.totalPasses > 0 {
        #expect(orientation == 0)
        try decoder.decode(block, orientation: orientation, roiShift: 0,
                           codeBlockStyle: 0, numBitPlanes: bitPlanes, budget: &budget); samples = decoder.outputArray()
        let width = block.x1 - block.x0
        for index in samples.indices {
            let x = block.x0 + index % width
            let y = block.y0 + index / width
            #expect(samples[index] / 2 + 128 == image.samples[y * image.width + x])
        }
    }
}

@Test func randomCodeBlockBytesDoNotTrap() throws {
    var budget = MemoryBudget(limit: 1 << 20)
    var decoder = try CodeBlockDecoder(maxWidth: 8, maxHeight: 8, budget: &budget)
    var state: UInt32 = 12345
    var samples: [Int32] = []
    for _ in 0..<100 {
        var block = CodeBlock(x0: 0, y0: 0, x1: 8, y1: 8)
        block.segments = [CodeBlockSegment(passes: 10, maxPasses: 10, length: 24, dataLength: 24)]
        block.data = (0..<24).map { _ in
            state = state &* 1664525 &+ 1013904223
            return UInt8(truncatingIfNeeded: state >> 24)
        }
        try decoder.decode(block, orientation: 0, roiShift: 0,
                           codeBlockStyle: 0, numBitPlanes: 4, budget: &budget); samples = decoder.outputArray()
        #expect(samples.count == 64)
    }
}

@Test func negativeNominalBitPlanesUseROISumBounds() throws {
    var budget = MemoryBudget(limit: 1 << 20)
    var decoder = try CodeBlockDecoder(maxWidth: 1, maxHeight: 1, budget: &budget)
    let block = CodeBlock(x0: 0, y0: 0, x1: 1, y1: 1)
    try decoder.decode(block, orientation: 0, roiShift: 2,
                       codeBlockStyle: 0, numBitPlanes: -1, budget: &budget)
    #expect(decoder.outputCount == 1)
    try decoder.decode(block, orientation: 0, roiShift: 31,
                       codeBlockStyle: 0, numBitPlanes: -1, budget: &budget)
    #expect(decoder.outputCount == 1)
    #expect(throws: JP2KError.invalidCodestream(.badCodeBlock)) {
        try decoder.decode(block, orientation: 0, roiShift: 1,
                           codeBlockStyle: 0, numBitPlanes: -2, budget: &budget)
    }
    #expect(throws: JP2KError.invalidCodestream(.badCodeBlock)) {
        try decoder.decode(block, orientation: 0, roiShift: 32,
                           codeBlockStyle: 0, numBitPlanes: -1, budget: &budget)
    }
}


@Test func codeBlockRejectsInvalidGeometryAndStyle() throws {
    var budget = MemoryBudget(limit: 1 << 20)
    #expect(throws: JP2KError.invalidCodestream(.badCodeBlock)) {
        _ = try CodeBlockDecoder(maxWidth: 65, maxHeight: 64, budget: &budget)
    }
    var decoder = try CodeBlockDecoder(maxWidth: 8, maxHeight: 8, budget: &budget)
    let block = CodeBlock(x0: 0, y0: 0, x1: 8, y1: 8)
    var samples: [Int32] = []
    #expect(throws: JP2KError.invalidCodestream(.badCodeBlock)) {
        try decoder.decode(block, orientation: 4, roiShift: 0, codeBlockStyle: 0,
                           numBitPlanes: 4, budget: &budget); samples = decoder.outputArray()
    }
    #expect(throws: JP2KError.invalidCodestream(.badCodeBlock)) {
        try decoder.decode(block, orientation: 0, roiShift: 0, codeBlockStyle: 0x40,
                           numBitPlanes: 4, budget: &budget); samples = decoder.outputArray()
    }
    #expect(throws: JP2KError.invalidCodestream(.badCodeBlock)) {
        try decoder.decode(block, orientation: 0, roiShift: 11, codeBlockStyle: 0,
                           numBitPlanes: 20, budget: &budget); samples = decoder.outputArray()
    }
    #expect(throws: JP2KError.invalidCodestream(.badCodeBlock)) {
        try decoder.decode(block, orientation: 0, roiShift: Int.max, codeBlockStyle: 0,
                           numBitPlanes: Int.max, budget: &budget); samples = decoder.outputArray()
    }
    var smallBudget = MemoryBudget(limit: 160)
    var constrained = try CodeBlockDecoder(maxWidth: 8, maxHeight: 8, budget: &smallBudget)
    // Scratch is grown (and charged) on first use and then retained; allocator
    // rounding makes its size platform-dependent. A repeated failure must not
    // charge anything further and must leave the output untouched.
    #expect(throws: JP2KError.limitExceeded(.memory)) {
        try constrained.decode(block, orientation: 0, roiShift: 0, codeBlockStyle: 0,
                               numBitPlanes: 4, budget: &smallBudget); samples = constrained.outputArray()
    }
    let afterFirstFailure = smallBudget.used
    #expect(constrained.outputArray().isEmpty)
    #expect(throws: JP2KError.limitExceeded(.memory)) {
        try constrained.decode(block, orientation: 0, roiShift: 0, codeBlockStyle: 0,
                               numBitPlanes: 4, budget: &smallBudget); samples = constrained.outputArray()
    }
    #expect(smallBudget.used == afterFirstFailure)
    #expect(constrained.outputArray().isEmpty)
}

@Test func codeBlockScratchBudgetIsReused() throws {
    let candidates = try blocks("gray-378x472-53.j2k")
    let block = try #require(candidates.first { $0.0.totalPasses > 0 })
    var measured = MemoryBudget(limit: 1 << 24)
    var decoder = try CodeBlockDecoder(maxWidth: 64, maxHeight: 64, budget: &measured)
    var samples: [Int32] = []
    try decoder.decode(block.0, orientation: block.1, roiShift: 0, codeBlockStyle: 0,
                       numBitPlanes: block.2, budget: &measured); samples = decoder.outputArray()
    let required = measured.used
    var exact = MemoryBudget(limit: required)
    var reused = try CodeBlockDecoder(maxWidth: 64, maxHeight: 64, budget: &exact)
    for _ in 0..<1_000 {
        try reused.decode(block.0, orientation: block.1, roiShift: 0, codeBlockStyle: 0,
                          numBitPlanes: block.2, budget: &exact)
        #expect(exact.used == required)
    }
    #expect(reused.outputArray() == samples)
}

extension CodeBlockDecoder {
    func outputArray() -> [Int32] {
        (0..<outputCount).map { output(at: $0) }
    }
}
